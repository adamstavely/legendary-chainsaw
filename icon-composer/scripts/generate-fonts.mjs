import fs from 'node:fs';
import opentype from 'opentype.js';
const fonts = {};
for (const family of ['roboto','roboto-mono']) {
  for (const weight of [400,700]) {
    const buffer=fs.readFileSync(`node_modules/@fontsource/${family}/files/${family}-latin-${weight}-normal.woff`);
    const font=opentype.parse(buffer.buffer.slice(buffer.byteOffset,buffer.byteOffset+buffer.byteLength));
    const glyphs={};
    for(let code=32;code<=255;code++) {
      if(code>=127&&code<=159)continue;
      const char=String.fromCharCode(code),glyph=font.charToGlyph(char);
      if(!glyph.index&&char!==' ')continue;
      glyphs[char]={advance:glyph.advanceWidth/font.unitsPerEm,commands:glyph.getPath(0,0,1).commands.map(c=>Object.fromEntries(Object.entries(c).map(([k,v])=>[k,typeof v==='number'?Number(v.toFixed(6)):v])))};
    }
    fonts[`${family==='roboto'?'sans':'mono'}-${weight}`]={label:`${family==='roboto'?'Roboto':'Roboto Mono'} ${weight===700?'Bold':'Regular'}`,capHeight:font.charToGlyph('H').yMax/font.unitsPerEm,glyphs};
  }
}
fs.writeFileSync('src/fonts.mjs','// Generated by scripts/generate-fonts.mjs. Roboto / Roboto Mono, SIL OFL 1.1.\nexport const fonts = '+JSON.stringify(fonts)+';\n');
