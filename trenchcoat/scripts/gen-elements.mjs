// Writes src/elements/index.ts and src/elements/react.ts from the files in src/elements/ and src/elements/react/, so
// adding an element never edits a shared list. `--check` fails when either file is out of date (CI).
import { readFileSync, readdirSync, writeFileSync } from "node:fs";

const ts = (dir, skip) => readdirSync(dir).filter((f) => f.endsWith(".ts") && !skip.includes(f)).map((f) => f.slice(0, -3)).sort();
// The provider and the pilot's three first, then the rest by name
const first = ["look-provider", "button", "combobox", "data-table"];
const order = (names) => [...first.filter((n) => names.includes(n)), ...names.filter((n) => !first.includes(n))];

const index = `// Trenchcoat elements – every element registers itself when its module loads. Generated by scripts/gen-elements.mjs.
// Exported type names carry the element's name (ComboboxOption, DataSort…), so they don't collide here
${order(ts("src/elements", ["index.ts", "react.ts"])).map((n) => `export * from "./${n}";`).join("\n")}
export { TcLookProvider, lookContext, type Look } from "./internal/look";
`;

const react = `/*
 * React wrappers for the Trenchcoat elements (decision L9) – \`import { Button, Combobox, DataTable } from
 * "trenchcoat/react"\`. One file per element in react/, the shared helpers in react/internal.ts; this list is
 * generated by scripts/gen-elements.mjs. They keep the React components' API:
 *   · <Button>Save</Button>: string children become the label; \`icon\` / \`iconRight\` render as slot="icon" children
 *   · value props are controlled when given: the wrapper calls preventDefault() on the element's change event and
 *     reports the change through the callback, so React state stays the source of truth (acceptance check 9);
 *     without them the element keeps its own state, starting at the default
 *   · \`title\` on DataTable is the table's heading (the element calls it \`heading\`, since \`title\` is a tooltip)
 *   · icons and logos may be React nodes, as before: the wrapper renders them into a hidden staging box and hands
 *     the element their DOM nodes, which it clones (the elements take icons as data – audit/lit-patterns.md)
 */
${order(ts("src/elements/react", ["internal.ts"])).map((n) => `export * from "./react/${n}";`).join("\n")}
`;

let stale = 0;
for (const [file, text] of [["src/elements/index.ts", index], ["src/elements/react.ts", react]]) {
  if (readFileSync(file, "utf8") === text) continue;
  if (process.argv.includes("--check")) {
    console.error(`${file} is out of date – run node scripts/gen-elements.mjs`);
    stale++;
  } else writeFileSync(file, text);
}
process.exit(stale ? 1 : 0);
